# 注释：导入 PyTorch 主库，用于张量计算、自动求导和模型训练。
import torch


# 注释：定义脚本主入口，把当前练习的数据、模型和训练流程串起来。
def main():
    # 注释：打印当前结果、模型信息或生成文本，方便观察运行状态。
    print("Autograd demo")
    # 注释：打印当前结果、模型信息或生成文本，方便观察运行状态。
    print("-" * 40)

    # 注释：把 Python 数据转换成 PyTorch 张量并保存到 `x`。
    x = torch.tensor(3.0, requires_grad=True)
    # 注释：将 `x**2 + 2 * x + 1` 这一步的结果保存到 `y`，供后续代码使用。
    y = x**2 + 2 * x + 1

    # 注释：根据损失反向传播，计算每个参数的梯度。
    y.backward()

    # 注释：打印当前结果、模型信息或生成文本，方便观察运行状态。
    print("Function: y = x^2 + 2x + 1")
    # 注释：打印当前结果、模型信息或生成文本，方便观察运行状态。
    print("x:", x.item())
    # 注释：打印当前结果、模型信息或生成文本，方便观察运行状态。
    print("y:", y.item())
    # 注释：打印当前结果、模型信息或生成文本，方便观察运行状态。
    print("dy/dx:", x.grad.item())
    # 注释：打印当前结果、模型信息或生成文本，方便观察运行状态。
    print("Expected dy/dx at x=3: 2 * 3 + 2 = 8")

    # 注释：打印当前结果、模型信息或生成文本，方便观察运行状态。
    print()
    # 注释：打印当前结果、模型信息或生成文本，方便观察运行状态。
    print("Vector example")
    # 注释：打印当前结果、模型信息或生成文本，方便观察运行状态。
    print("-" * 40)

    # 注释：把 Python 数据转换成 PyTorch 张量并保存到 `a`。
    a = torch.tensor([1.0, 2.0, 3.0], requires_grad=True)
    # 注释：将 `(a * a).sum()` 这一步的结果保存到 `b`，供后续代码使用。
    b = (a * a).sum()

    # 注释：根据损失反向传播，计算每个参数的梯度。
    b.backward()

    # 注释：打印当前结果、模型信息或生成文本，方便观察运行状态。
    print("Function: b = sum(a * a)")
    # 注释：打印当前结果、模型信息或生成文本，方便观察运行状态。
    print("a:", a.detach())
    # 注释：打印当前结果、模型信息或生成文本，方便观察运行状态。
    print("b:", b.item())
    # 注释：打印当前结果、模型信息或生成文本，方便观察运行状态。
    print("db/da:", a.grad)
    # 注释：打印当前结果、模型信息或生成文本，方便观察运行状态。
    print("Expected db/da: 2 * a")


# 注释：判断当前文件是否被直接运行，直接运行时才调用 main。
if __name__ == "__main__":
    # 注释：调用主函数，启动当前脚本的完整练习流程。
    main()
